-- Deduction reasons are managed centrally so every site evaluates the same
-- grain-specific rule. A rule produces one deduction item for a trip; a grain
-- can have several rules (percentage moisture plus fixed-amount impurity).
CREATE TABLE grain_deduction_category (
 code VARCHAR(40) PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 sort_order INTEGER NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE grain_deduction_rule (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(40) NOT NULL UNIQUE,
 material_code VARCHAR(80) NOT NULL REFERENCES wb_cloud_material(code) ON UPDATE CASCADE,
 category_code VARCHAR(40) NOT NULL REFERENCES grain_deduction_category(code) ON UPDATE CASCADE,
 mode VARCHAR(20) NOT NULL CHECK (mode IN ('amount','percent')),
 basis_field VARCHAR(20) NOT NULL DEFAULT '' CHECK (basis_field IN ('','moisture','impurity','bulk_density')),
 amount_milli_tonne BIGINT NOT NULL DEFAULT 0 CHECK (amount_milli_tonne >= 0),
 version BIGINT NOT NULL DEFAULT 1,
 effective_from TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 enabled BOOLEAN NOT NULL DEFAULT TRUE,
 remark TEXT NOT NULL DEFAULT '',
 created_by BIGINT REFERENCES sys_user(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_by BIGINT REFERENCES sys_user(id),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (mode <> 'percent' OR basis_field <> ''),
 CHECK (mode <> 'amount' OR amount_milli_tonne >= 0)
);

CREATE TABLE grain_deduction_rule_range (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 rule_id BIGINT NOT NULL REFERENCES grain_deduction_rule(id) ON DELETE CASCADE,
 min_value NUMERIC(12,6) NOT NULL CHECK (min_value >= 0),
 max_value NUMERIC(12,6),
 rate_bp INTEGER NOT NULL CHECK (rate_bp BETWEEN 0 AND 10000),
 sort_order INTEGER NOT NULL,
 UNIQUE (rule_id, sort_order),
 CHECK (max_value IS NULL OR max_value > min_value)
);

CREATE INDEX idx_grain_deduction_rule_material ON grain_deduction_rule(material_code, enabled);
CREATE INDEX idx_grain_deduction_rule_category ON grain_deduction_rule(category_code);

