-- +goose Up
-- The mobile first/second weigh is now a handoff to the factory station. The
-- mobile session only tracks the QR handoff and the factory result; the final
-- ticket is created and synced by the factory.
ALTER TABLE grain_outbound_weighing
  ADD COLUMN source varchar(20) NOT NULL DEFAULT 'mobile_direct',
  ADD COLUMN factory_task_no varchar(100) NOT NULL DEFAULT '',
  ADD COLUMN net_milli_tonne bigint NOT NULL DEFAULT 0,
  ADD COLUMN capture_status varchar(20) NOT NULL DEFAULT '',
  ADD COLUMN message text NOT NULL DEFAULT '',
  ADD COLUMN expires_at timestamp with time zone;

DROP INDEX IF EXISTS uk_grain_outbound_pending;

CREATE UNIQUE INDEX uk_grain_outbound_active
  ON grain_outbound_weighing (user_id)
  WHERE status IN ('first_qr_ready', 'first_scanning', 'first_recorded', 'second_qr_ready', 'second_scanning');

CREATE TABLE grain_outbound_handoff (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  weighing_id bigint NOT NULL REFERENCES grain_outbound_weighing(id) ON DELETE CASCADE,
  action varchar(10) NOT NULL CHECK (action IN ('first', 'second')),
  token_hash char(64) NOT NULL UNIQUE,
  status varchar(20) NOT NULL DEFAULT 'issued',
  expires_at timestamp with time zone NOT NULL,
  claimed_at timestamp with time zone,
  completed_at timestamp with time zone,
  result jsonb,
  created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_grain_outbound_handoff_weighing
  ON grain_outbound_handoff (weighing_id, action, id DESC);

